-- Hyprland configuration (Lua format, Hyprland >= 0.55).
-- The old hyprlang `.conf` format is deprecated; everything here mirrors what
-- used to live in hyprland.conf and the files it sourced.

-- Hardware cursors: let the display engine draw the cursor instead of
-- re-compositing the whole framebuffer on every mouse move. Critical for
-- the 5120x2160 ultrawide (DP-4) driven by the Intel iGPU — software
-- cursors made the desktop feel laggy. The old NVIDIA mixed-scaling glitch
-- this used to work around no longer applies (the ultrawide is on Intel,
-- and the dGPU drives no display). Re-enable software cursors only if
-- cursor artifacts return.
hl.config({
    cursor = {
        no_hardware_cursors = false,
        -- The pointer stays where it was put. By default a focus change by
        -- key (ALT + H/J/K/L, the overview) carries it to the middle of the
        -- newly focused window. With input.follow_mouse = 2 the focus does
        -- not depend on where the pointer is, so nothing needs it there.
        no_warps = true,
    },
})

hl.config({
    xwayland = {
        -- Tells XWayland apps to handle their own scaling
        -- This can make them sharp, but some may be tiny.
        force_zero_scaling = true,
    },
})

-- Each require() gets its own Lua scope, so an error in one file does not
-- abort the others.
require("monitors")
require("workspaces")
require("input")
require("bindings")
require("envs")
require("looknfeel")
require("autostart")
require("plugins")

-- Palette module generated by Noctalia's hyprland template into
-- ~/.config/hypr/noctalia.lua (not tracked here). Must come last so it wins
-- over the colours set above. Guarded so a missing file, e.g. before
-- Noctalia's first run, keeps Hyprland's defaults instead of erroring out.
-- Noctalia's apply.sh checks for the literal require("noctalia") below, so
-- keep it intact or it will append an unguarded copy.
local ok, theme = pcall(function() return require("noctalia") end)
if ok and require("dotfiles_theme") == "acid" then
    theme.apply_theme()
    -- ACID//HUD: primary -> secondary -> primary gradient on the active border (the
    -- borderangle loop in looknfeel.lua spins it), a dim hairline on inactive
    -- windows, and a primary-tinted shadow as a glow. Re-read on every reload, so
    -- the colors_changed hook in noctalia config.toml keeps it in step.
    local primary_hex = theme.colors.primary:match("%x%x%x%x%x%x") or "ef5fc6"
    hl.config({
        general = {
            border_size = 2,
            col = {
                active_border = {
                    colors = { theme.colors.primary, theme.colors.secondary, theme.colors.primary },
                    angle = 45,
                },
                inactive_border = "rgba(4a3a62aa)",
            },
        },
        decoration = {
            shadow = { color = "rgba(" .. primary_hex .. "30)" },
        },
    })
elseif ok then
    theme.apply_theme()
    -- Classic: the template's flat active border becomes a primary -> secondary
    -- gradient. Re-read on every reload, so the colors_changed hook in noctalia
    -- config.toml keeps it in step with the palette.
    hl.config({
        general = {
            border_size = 2,
            col = {
                active_border = {
                    colors = { theme.colors.primary, theme.colors.secondary },
                    angle = 45,
                },
            },
        },
    })
end
